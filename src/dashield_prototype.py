def fill(t):
    return t.format(ag=random.choice(AGENCY), off=random.choice(OFFICER), city=random.choice(CITY),
                    amt=random.choice(AMT), nm=random.choice(NAME), n=random.randint(200, 90000),
                    d4=random.randint(1000, 9999), d6=random.randint(100000, 999999),
                    date=f"{random.randint(1,28):02d}-0{random.randint(1,9)}", who=random.choice(["swiggy", "ravi", "msedcl", "zomato"]))

def noisy(s):
    r = random.random()
    if r < 0.25: s = s.lower()
    if random.random() < 0.20:                     # drop a random word
        w = s.split(); w.pop(random.randrange(len(w))); s = " ".join(w)
    if random.random() < 0.15:                     # swap two adjacent characters (typo)
        i = random.randrange(1, len(s) - 1); s = s[:i-1] + s[i] + s[i-1] + s[i+1:]
    return s

def build_corpus(per_family=70):
    rows = []
    for fam, temps in SCAM.items():
        for _ in range(per_family): rows.append((noisy(fill(random.choice(temps))), 1, fam))
    for fam, temps in LEGIT.items():
        for _ in range(per_family): rows.append((noisy(fill(random.choice(temps))), 0, fam))
    random.shuffle(rows)
    return rows

RED_FLAGS = ["digital arrest", "arrest", "cbi", "ed ", "money laundering", "do not disconnect", "video call",
             "do not inform", "tell nobody", "kisi ko mat", "safe custody", "verification account", "refund",
             "warrant", "secrecy", "drugs", "mdma", "aadhaar", "transfer", "fixed deposit", "camera"]

def rule_baseline(texts, k=3):
    out = []
    for t in texts:
        tl = t.lower(); out.append(1 if sum(f in tl for f in RED_FLAGS) >= k else 0)
    return np.array(out)

def make_lr():
    feats = make_union(TfidfVectorizer(ngram_range=(1, 2), sublinear_tf=True, min_df=1),
                       TfidfVectorizer(analyzer="char_wb", ngram_range=(3, 5), sublinear_tf=True))
    return make_pipeline(feats, LogisticRegression(max_iter=2000, C=4.0, class_weight="balanced"))

def make_nb():
    return make_pipeline(TfidfVectorizer(ngram_range=(1, 2)), MultinomialNB(alpha=0.3))

def leave_family_out(rows):
    """Each fold holds out one scam family AND one legit family entirely, so the
    test messages come from templates the model has never seen."""
    texts = np.array([r[0] for r in rows]); y = np.array([r[1] for r in rows]); fam = np.array([r[2] for r in rows])
    s_f, l_f = list(SCAM), list(LEGIT)
    folds = [(s_f[i % len(s_f)], l_f[i % len(l_f)]) for i in range(max(len(s_f), len(l_f)))]
    agg = {m: {"y": [], "p": [], "s": []} for m in ["Rule baseline", "TF-IDF + Naive Bayes", "TF-IDF + Logistic Regression"]}
    per_fold = []
    for sf, lf in folds:
        te = (fam == sf) | (fam == lf); tr = ~te
        lr = make_lr().fit(texts[tr], y[tr]); nb = make_nb().fit(texts[tr], y[tr])
        preds = {"Rule baseline": (rule_baseline(texts[te]), None),
                 "TF-IDF + Naive Bayes": (nb.predict(texts[te]), nb.predict_proba(texts[te])[:, 1]),
                 "TF-IDF + Logistic Regression": (lr.predict(texts[te]), lr.predict_proba(texts[te])[:, 1])}
        f_row = {"held_out": f"{sf} + {lf}"}
        for m, (p, s) in preds.items():
            agg[m]["y"] += list(y[te]); agg[m]["p"] += list(p)
            if s is not None: agg[m]["s"] += list(s)
            f_row[m] = round(precision_recall_fscore_support(y[te], p, average="binary", zero_division=0)[2], 3)
        per_fold.append(f_row)
    summary = {}
    for m, d in agg.items():
        p, r, f, _ = precision_recall_fscore_support(d["y"], d["p"], average="binary", zero_division=0)
        acc = float(np.mean(np.array(d["y"]) == np.array(d["p"])))
        auc = roc_auc_score(d["y"], d["s"]) if d["s"] else None
        summary[m] = {"accuracy": round(acc, 3), "precision": round(p, 3), "recall": round(r, 3), "f1": round(f, 3),
                      "roc_auc": round(auc, 3) if auc else None, "cm": confusion_matrix(d["y"], d["p"]).tolist()}
    return summary, per_fold

