# MODULE C - replay of the reconstructed Pune case (illustrative split of Rs 4.37 cr)
# ------------------------------------------------------------------
CASE = [  # day, amount (Rs), liquidated FD/MF in last 48h, new payee, payee account age (days)
    (1, 25_00_000, True, True, 40), (2, 48_00_000, True, True, 65), (4, 72_00_000, True, True, 22),
    (6, 95_00_000, False, True, 90), (9, 1_12_00_000, True, True, 15), (12, 85_00_000, True, False, 15)]

def replay_case():
    rows, burst, cum = [], 0, 0
    for i, (day, amt, liq, newp, age_acct) in enumerate(CASE):
        burst = 1 + sum(1 for d, *_ in CASE[:i] if day - d <= 3)
        tx = {"age": 78, "avg_90d": 40_000, "amount": amt, "new_payee": newp, "payee_acct_age_days": age_acct,
              "liquidated_48h": liq, "high_value_72h": burst, "on_call_at_branch": False}
        sc, f = risk_score(tx); cum += amt
        rows.append({"step": i + 1, "day": day, "amount_lakh": amt / 1e5, "cumulative_lakh": cum / 1e5,
                     "score": sc, "action": action(sc), "fired": [k for k, v in f.items() if v]})
    return rows

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "outputs")

