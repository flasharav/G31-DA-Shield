# MODULE B - elderly transaction risk engine
# ------------------------------------------------------------------
WEIGHTS = {  # points out of 100; justified in report Table 4
    "senior": 10, "amount_ratio_high": 20, "new_payee": 15, "young_payee_acct": 15,
    "fd_or_mf_liquidated_48h": 15, "burst_72h": 15, "staff_flag_on_call": 10}
HOLD, VERIFY = 60, 40

def features(tx):
    return {"senior": int(tx["age"] >= 60),
            "amount_ratio_high": int(tx["amount"] >= 5 * max(tx["avg_90d"], 1)),
            "new_payee": int(tx["new_payee"]),
            "young_payee_acct": int(tx["payee_acct_age_days"] < 180),
            "fd_or_mf_liquidated_48h": int(tx["liquidated_48h"]),
            "burst_72h": int(tx["high_value_72h"] >= 2),
            "staff_flag_on_call": int(tx["on_call_at_branch"])}

def risk_score(tx):
    f = features(tx); return sum(WEIGHTS[k] * v for k, v in f.items()), f

def action(score):
    return "HOLD 24h + trusted-contact callback" if score >= HOLD else ("Teller verification script" if score >= VERIFY else "Allow")

def simulate_population(n_customers=4000, n_campaigns=150):
    tx, cust_id = [], 0
    for _ in range(n_customers):                     # legitimate elderly customers
        cust_id += 1; age = random.randint(60, 90); avg = random.lognormvariate(10.3, 0.7)  # ~30k
        for _ in range(random.randint(3, 8)):
            big = random.random() < 0.04             # occasional genuine large payment
            amt = avg * (random.uniform(5, 40) if big else random.uniform(0.1, 2.5))
            tx.append({"cust": cust_id, "age": age, "avg_90d": avg, "amount": amt, "label": 0,
                       "new_payee": random.random() < (0.45 if big else 0.12),
                       "payee_acct_age_days": random.choice([random.randint(30, 179)] if random.random() < 0.08 else [random.randint(180, 6000)]),
                       "liquidated_48h": big and random.random() < 0.30,
                       "high_value_72h": 1 + int(big and random.random() < 0.15),
                       "on_call_at_branch": random.random() < 0.02})
    for _ in range(n_campaigns):                     # digital-arrest campaigns
        cust_id += 1; age = random.randint(60, 88); avg = random.lognormvariate(10.3, 0.7)
        k = random.randint(2, 9); prev = 0
        for i in range(k):
            amt = random.uniform(3e5, 1.2e7); prev += 1
            tx.append({"cust": cust_id, "age": age, "avg_90d": avg, "amount": amt, "label": 1,
                       "new_payee": random.random() < 0.85,
                       "payee_acct_age_days": random.randint(5, 170) if random.random() < 0.7 else random.randint(180, 1500),
                       "liquidated_48h": random.random() < 0.65,
                       "high_value_72h": min(prev, 3),
                       "on_call_at_branch": random.random() < 0.25})
    return tx

def evaluate_engine(tx):
    y = np.array([t["label"] for t in tx]); s = np.array([risk_score(t)[0] for t in tx])
    res = {}
    for name, thr in [("VERIFY (>=40)", VERIFY), ("HOLD (>=60)", HOLD)]:
        p = (s >= thr).astype(int); pr, rc, f1, _ = precision_recall_fscore_support(y, p, average="binary")
        fpr = float(((p == 1) & (y == 0)).sum() / (y == 0).sum())
        res[name] = {"precision": round(pr, 3), "recall": round(rc, 3), "f1": round(f1, 3), "fpr": round(fpr, 4)}
    res["roc_auc"] = round(roc_auc_score(y, s), 3)
    # campaign-level: was the FIRST installment of each campaign held?
    first = {}
    for t in tx:
        if t["label"] == 1 and t["cust"] not in first: first[t["cust"]] = t
    stopped = sum(risk_score(t)[0] >= HOLD for t in first.values())
    flagged_any = len({t["cust"] for t in tx if t["label"] == 1 and risk_score(t)[0] >= HOLD})
    res["campaigns"] = len(first); res["stopped_at_first_installment"] = stopped
    res["stopped_at_some_installment"] = flagged_any
    # money that would not have left if every HOLD was effective
    lost = {}; saved = 0.0; total = 0.0
    for t in tx:
        if t["label"] != 1: continue
        total += t["amount"]
        if t["cust"] in lost: saved += t["amount"]; continue
        if risk_score(t)[0] >= HOLD: lost[t["cust"]] = True; saved += t["amount"]
    res["fraud_value_total_cr"] = round(total / 1e7, 2); res["fraud_value_prevented_cr"] = round(saved / 1e7, 2)
    # ML comparison (customer-grouped split)
    X = np.array([[t["age"], np.log1p(t["amount"]), np.log1p(t["avg_90d"]), t["new_payee"], t["payee_acct_age_days"],
                   t["liquidated_48h"], t["high_value_72h"], t["on_call_at_branch"]] for t in tx], dtype=float)
    cust = np.array([t["cust"] for t in tx]); uc = np.unique(cust); rng = np.random.default_rng(SEED)
    test_c = set(rng.choice(uc, size=len(uc) // 3, replace=False)); te = np.array([c in test_c for c in cust])
    rf = RandomForestClassifier(n_estimators=300, random_state=SEED, class_weight="balanced", min_samples_leaf=3).fit(X[~te], y[~te])
    rp = rf.predict(X[te]); pr, rc, f1, _ = precision_recall_fscore_support(y[te], rp, average="binary")
    fpr = float(((rp == 1) & (y[te] == 0)).sum() / (y[te] == 0).sum())
    rule_te = (s[te] >= HOLD).astype(int); pr2, rc2, f2, _ = precision_recall_fscore_support(y[te], rule_te, average="binary")
    fpr2 = float(((rule_te == 1) & (y[te] == 0)).sum() / (y[te] == 0).sum())
    res["test_split"] = {"Rule engine (HOLD)": {"precision": round(pr2, 3), "recall": round(rc2, 3), "f1": round(f2, 3), "fpr": round(fpr2, 4)},
                         "Random Forest": {"precision": round(pr, 3), "recall": round(rc, 3), "f1": round(f1, 3), "fpr": round(fpr, 4),
                                           "roc_auc": round(roc_auc_score(y[te], rf.predict_proba(X[te])[:, 1]), 3)}}
    res["n_tx"] = len(tx); res["n_fraud_tx"] = int(y.sum())
    return res, s, y

